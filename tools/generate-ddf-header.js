#!/usr/bin/env node
// Regenerates src/ddf_zip.h from the designer repo's DDF, and keeps
// DeviceInfo.h's DDF_VERSION in sync with the version inside it.
//
// This used to be "a one-off script" that was never checked in, which is
// exactly why the two drifted: the designer's DDF went 1.4 -> 1.5 -> 1.6
// while this firmware kept announcing and serving 1.4, so a designer that
// picked this device from "Announced Devices" got a DDF missing object
// types the firmware had actually gained.
//
// Run after any change to the designer's public/ddf/m5stack-m5dial.ddf.zip,
// then rebuild and flash - the header is compiled in, so a rebuild is what
// actually publishes it:
//
//   node tools/generate-ddf-header.js
//   pio run -e m5dial -t upload
//
// Pass --check to verify without writing (exit 1 on drift).

const fs = require("fs")
const path = require("path")

const REPO = path.join(__dirname, "..")
const DEFAULT_DDF = path.join(REPO, "..", "v0-screenman-editor-design", "public", "ddf", "m5stack-m5dial.ddf.zip")
const HEADER = path.join(REPO, "src", "ddf_zip.h")
const DEVICE_INFO = path.join(REPO, "src", "DeviceInfo.h")

const checkOnly = process.argv.includes("--check")
const ddfPath = process.argv.find((a) => a.endsWith(".zip")) || DEFAULT_DDF

if (!fs.existsSync(ddfPath)) {
  console.error(`DDF not found: ${ddfPath}`)
  console.error("Pass an explicit path if the designer repo isn't checked out next to this one.")
  process.exit(1)
}

const zip = fs.readFileSync(ddfPath)

// device.json's ddfVersion, read straight out of the zip. Only stored
// entries would be readable as-is, and the designer writes DEFLATE, so
// inflate the entry properly rather than pattern-matching the raw bytes.
function readDdfVersion(buf) {
  const zlib = require("zlib")
  let offset = 0
  while (offset < buf.length - 4) {
    if (buf.readUInt32LE(offset) !== 0x04034b50) break
    const method = buf.readUInt16LE(offset + 8)
    const compressedSize = buf.readUInt32LE(offset + 18)
    const nameLen = buf.readUInt16LE(offset + 26)
    const extraLen = buf.readUInt16LE(offset + 28)
    const name = buf.slice(offset + 30, offset + 30 + nameLen).toString("utf8")
    const dataStart = offset + 30 + nameLen + extraLen
    if (name === "device.json") {
      const raw = buf.slice(dataStart, dataStart + compressedSize)
      const json = method === 0 ? raw : zlib.inflateRawSync(raw)
      return JSON.parse(json.toString("utf8")).ddfVersion
    }
    offset = dataStart + compressedSize
  }
  throw new Error("device.json not found in the DDF zip")
}

const version = readDdfVersion(zip)

const lines = []
for (let i = 0; i < zip.length; i += 16) {
  const row = Array.from(zip.slice(i, i + 16))
    .map((b) => `0x${b.toString(16).padStart(2, "0")}`)
    .join(", ")
  lines.push(`  ${row},`)
}

const header = `#pragma once
// public/ddf/m5stack-m5dial.ddf.zip (designer repo), embedded verbatim -
// GENERATED by tools/generate-ddf-header.js, do not hand-edit. Served at
// GET /ddf.zip (TestInterfaceServer) so the designer's
// device-scan-section.tsx can fetch+cache this device's own DDF directly
// from a live device, the same way the e-paper firmware already does.
//
// Regenerate whenever the DDF file changes - the generator also bumps
// DeviceInfo.h's DDF_VERSION, which is what tells the designer a cached
// copy is stale and needs refetching.
//
// DDF version embedded here: ${version}
static const uint8_t DDF_ZIP[${zip.length}] = {
${lines.join("\n")}
};
`

const existingHeader = fs.existsSync(HEADER) ? fs.readFileSync(HEADER, "utf8") : ""
const deviceInfo = fs.readFileSync(DEVICE_INFO, "utf8")
const versionPattern = /#define DDF_VERSION "([^"]*)"/
const currentVersion = (deviceInfo.match(versionPattern) || [])[1]

if (checkOnly) {
  const headerStale = existingHeader !== header
  const versionStale = currentVersion !== version
  if (headerStale || versionStale) {
    if (headerStale) console.error(`src/ddf_zip.h is stale (DDF is ${zip.length} bytes, version ${version})`)
    if (versionStale) console.error(`DeviceInfo.h DDF_VERSION is "${currentVersion}", DDF says "${version}"`)
    console.error("Run: node tools/generate-ddf-header.js")
    process.exit(1)
  }
  console.log(`Up to date (DDF version ${version}, ${zip.length} bytes)`)
  process.exit(0)
}

fs.writeFileSync(HEADER, header)
if (currentVersion !== version) {
  fs.writeFileSync(DEVICE_INFO, deviceInfo.replace(versionPattern, `#define DDF_VERSION "${version}"`))
  console.log(`DDF_VERSION ${currentVersion} -> ${version}`)
}
console.log(`Wrote src/ddf_zip.h (${zip.length} bytes) from ${ddfPath}`)
